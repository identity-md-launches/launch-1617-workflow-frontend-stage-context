export const territories = names.map((name, id) => ({
  id,
  name,
  x: coords[id][0],
  y: coords[id][1],
  continent: continents.findIndex(
    (c) => id >= c.first && id < c.first + c.count,
  ),
  adjacent: links
    .filter((e) => e.includes(id))
    .map((e) => (e[0] === id ? e[1] : e[0])),
}));
export const bridges = links.filter(
  ([a, b]) => territories[a].continent !== territories[b].continent,
);
